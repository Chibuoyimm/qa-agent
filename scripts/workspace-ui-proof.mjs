// Only inference is substituted. Tasks, discovery, proposal persistence, approval,
// browser execution, evidence, recheck and coverage use the real local services.
import assert from 'node:assert/strict';
import { resolve } from 'node:path';

export async function verifyWorkspaceUI(page, api, templates, goodURL, badURL, waitRun, evidence, apiToken, insertFixtureTurn) {
  await page.unroute('**/api/ai/config');
  await page.route('**/api/ai/config', route => route.fulfill({ json: {provider:'openai',models:['workspace-fixture'],managed_available:false,byok_available:true} }));
  const app = await api('/api/projects',{name:'Task workspace proof',base_url:badURL});
  const setup = await api(`/api/projects/${app.id}/scenarios`, {...templates[0],name:'Access setup',expected_outcome:'Dashboard opens',steps:[...templates[0].steps.slice(0,4),{action:'assert_visible',test_id:'dashboard-revenue'}]});
  await api(`/api/projects/${app.id}/journeys`,{name:'Permissions'});
  await api(`/api/projects/${app.id}/journeys`,{name:'Invitations'});
  let calls=0;
  const chatPattern=`**/api/projects/${app.id}/tasks/*/chat`;
  await page.route(chatPattern,async route=>{
    if(route.request().method()==='GET')return route.continue();
    const input=route.request().postDataJSON(); calls++;
    assert.equal(input.consent,true);
    assert.equal(route.request().headers()['x-qa-provider-key'],'workspace-transient-key');
    const taskID=route.request().url().split('/tasks/')[1].split('/')[0];
    const task=await api(`/api/projects/${app.id}/tasks/${taskID}`);
    const discovery=await api(`/api/discoveries/${task.discovery_id}`);
    assert.equal(discovery.status,'completed');
    assert.equal(discovery.setup_scenario.id,setup.id);
    const proposal={provider:'openai',model:'workspace-fixture',context_sha256:'fixture',discovery_id:discovery.id,scenarios:calls===1?[]:templates.slice(0,3).map(item=>({...item,approved:false})),questions:calls===1?['What is the approved revenue?']:[],assumptions:[]};
    insertFixtureTurn({id:input.request_id,project_id:app.id,task_id:taskID,prompt:input.prompt,proposal});
    const turn=(await api(`/api/projects/${app.id}/tasks/${taskID}/chat`)).turns.find(item=>item.id===input.request_id);
    await route.fulfill({json:turn});
  });
  await page.reload();
  await page.getByLabel('Workspace access token',{exact:true}).fill(apiToken);
  await page.getByRole('button',{name:'Open workspace',exact:true}).click();
  await page.getByRole('combobox',{name:'Current app',exact:true}).selectOption(app.id);
  await page.getByRole('button',{name:'Test',exact:true}).click();
  await page.getByText('Journey · New journey',{exact:true}).click();
  await page.getByRole('textbox',{name:'Journey name (optional)',exact:true}).fill('Revenue reporting');
  await page.getByText('App access & exploration',{exact:true}).click();
  await page.getByRole('combobox',{name:'Sign-in or access setup',exact:true}).selectOption(setup.id);
  await page.locator('.chat-model-settings:visible > summary').click();
  await page.getByLabel('OpenAI API key',{exact:true}).filter({visible:true}).fill('workspace-transient-key');
  await page.getByRole('textbox',{name:'Your message',exact:true}).fill('Test revenue reporting');
  await page.getByRole('checkbox',{name:/I agree to send this message/}).check();
  await page.getByRole('button',{name:'Send message',exact:true}).click();
  await page.getByText('What is the approved revenue?',{exact:true}).waitFor({timeout:90000});
  await page.getByRole('textbox',{name:'Your message',exact:true}).fill('Paid 150000 less 10000 refunded equals 140000. Cancelled 90000 contributes nothing. Also check the order count and refund classification.');
  await page.getByLabel('OpenAI API key',{exact:true}).filter({visible:true}).fill('workspace-transient-key');
  await page.getByRole('checkbox',{name:/I agree to send this message/}).check();
  await page.getByRole('button',{name:'Send message',exact:true}).click();
  await page.getByRole('heading',{name:'3 checks selected',exact:true}).waitFor();
  await page.getByRole('checkbox',{name:`3. ${templates[2].name}`,exact:true}).uncheck();
  const reviewedOutcome='Exactly three independently seeded orders are displayed.';
  await page.getByRole('textbox',{name:'Expected outcome',exact:true}).nth(1).fill(reviewedOutcome);
  await page.getByRole('heading',{name:'2 checks selected',exact:true}).waitFor();
  await page.reload();
  await page.getByLabel('Workspace access token',{exact:true}).fill(apiToken);
  await page.getByRole('button',{name:'Open workspace',exact:true}).click();
  await page.getByRole('heading',{name:'2 checks selected',exact:true}).waitFor();
  assert.equal(await page.getByRole('textbox',{name:'Expected outcome',exact:true}).nth(1).inputValue(),reviewedOutcome,'Unapproved review edits survive reload');
  await page.getByRole('button',{name:'Approve & run 2 checks',exact:true}).click();
  const taskID=new URLSearchParams(page.url().split('?')[1]).get('task');
  let first;
  for(let i=0;i<100;i++){
    const chat=await api(`/api/projects/${app.id}/tasks/${taskID}/chat`);
    const runID=chat.turns.at(-1)?.run_id;
    if(runID){first=await waitRun(runID);break;}
    await new Promise(resolve=>setTimeout(resolve,100));
  }
  assert.equal(first?.status,'failed');
  assert.equal(first.scenarios.length,2);
  assert.equal(first.scenarios[1].expected_outcome,reviewedOutcome);
  await page.getByRole('button',{name:'Open results and evidence',exact:true}).click();
  await page.getByRole('heading',{name:'2 checks · failed',exact:true}).waitFor();
  await page.getByText('Observed: “230000”',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Open final screenshot',exact:true}).click();
  await page.getByRole('img',{name:`Final browser view for ${templates[0].name}`,exact:true}).waitFor();
  assert.match(await page.getByRole('img',{name:`Final browser view for ${templates[0].name}`,exact:true}).getAttribute('src'),/^blob:/);
  await page.getByRole('combobox',{name:'Decision',exact:true}).selectOption('Confirmed issue');
  await page.getByRole('textbox',{name:'Review note',exact:true}).fill('Independent revenue expectation is not met.');
  await page.getByRole('button',{name:'Save review',exact:true}).click();
  await page.getByText('Review saved. The recorded result and approved expectation are unchanged.',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Recheck a deployment',exact:true}).click();
  await page.getByRole('textbox',{name:'Deployed app URL',exact:true}).fill(goodURL);
  await page.getByRole('button',{name:'Run 2 checks',exact:true}).click();
  await page.getByRole('heading',{name:'2 checks · passed',exact:true}).waitFor({timeout:90000});
  const nextID=new URLSearchParams(page.url().split('?')[1]).get('run');
  const next=await api(`/api/runs/${nextID}`);
  assert.equal(next.source_run_id,first.id);
  assert.deepEqual(next.scenarios,first.scenarios,'Recheck must copy the frozen snapshot verbatim');
  assert.equal((await api(`/api/projects/${app.id}/scenarios`)).length,3,'Approval retry must not duplicate saved checks');
  await page.getByRole('button',{name:'Coverage',exact:true}).click();
  await page.getByRole('heading',{name:'2 checks ran across 1 journey',exact:true}).waitFor();
  await page.getByText('2 journeys still untested',{exact:true}).waitFor();
  await page.getByText('Permissions · Invitations',{exact:true}).waitFor();
  await page.screenshot({path:resolve(evidence,'task-coverage-desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'Task coverage fits mobile');
  await page.screenshot({path:resolve(evidence,'task-coverage-mobile.png'),fullPage:true});
  await page.setViewportSize({width:1440,height:1000});
  await page.reload();
  await page.getByLabel('Workspace access token',{exact:true}).fill(apiToken);
  await page.getByRole('button',{name:'Open workspace',exact:true}).click();
  await page.getByRole('button',{name:'Test',exact:true}).click();
  await page.getByText(reviewedOutcome,{exact:true}).waitFor();
  const saved=await api(`/api/projects/${app.id}/tasks/${taskID}`);
  assert.equal(saved.approvals.length,1);
  assert.equal(saved.approvals[0].scenario_ids.length,2);
  assert.equal(calls,2,'Run, review, recheck and reload do not call a model');
  await page.unroute(chatPattern);
  return {name:'Task questions, real discovery, edited/selective batch approval, real failure/evidence, finding review, frozen deployment recheck, unique journey coverage and reload persistence',status:'passed'};
}
